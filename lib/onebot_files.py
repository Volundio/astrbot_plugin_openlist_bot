import asyncio
import json
import os
import posixpath
import re
from typing import Callable, Dict, List, Optional, Tuple
from urllib.parse import parse_qs, unquote, urlparse

from astrbot.api import logger


CQ_SEGMENT_RE = re.compile(r"\[CQ:([a-zA-Z0-9_]+)(?:,([^\]]*))?\]")
FLASH_URL_RE = re.compile(r"https?://(?:[\w.-]*\.)?qfile\.qq\.com/[^\s\"'<>\]\\]+", re.IGNORECASE)

FLASH_SEGMENT_TYPES = {"flashtransfer", "flash_transfer", "flashfile"}
MEDIA_UPLOAD_SEGMENT_TYPES = {"file", "image", "video"}


def read_field(obj, key: str, default=None):
    """Safely read a key or attribute from dict/object/mapping."""
    if obj is None:
        return default
    if isinstance(obj, dict):
        return obj.get(key, default)
    value = getattr(obj, key, default)
    if value is not default:
        return value
    try:
        return obj[key]
    except Exception:
        return default


def to_int_or_none(value) -> Optional[int]:
    if value in (None, "") or isinstance(value, bool):
        return None
    try:
        return int(value)
    except (TypeError, ValueError):
        return None


def maybe_int_id(value):
    """Convert pure numeric IDs to int for OneBot 11 while preserving string IDs."""
    if isinstance(value, int) and not isinstance(value, bool):
        return value
    text = str(value or "").strip()
    if text.isdigit():
        return int(text)
    return text


def is_http_url(value) -> bool:
    return isinstance(value, str) and value.strip().startswith(("http://", "https://"))


def unwrap_action_data(res):
    """Unwrap OneBot raw response envelope if present; aiocqhttp usually returns data directly."""
    if isinstance(res, dict) and "data" in res and ("retcode" in res or "status" in res):
        return res.get("data")
    return res


def get_bot_caller(bot_or_event) -> Optional[Callable]:
    """Return bot.api.call_action coroutine function if available."""
    bot = getattr(bot_or_event, "bot", bot_or_event)
    api = getattr(bot, "api", None)
    call_action = getattr(api, "call_action", None)
    return call_action if callable(call_action) else None


async def call_onebot_action(bot_or_event, action: str, **params):
    """Invoke a OneBot action and unwrap its data payload."""
    caller = get_bot_caller(bot_or_event)
    if not caller:
        raise RuntimeError("当前平台适配器不支持 OneBot API 调用")
    clean_params = {k: v for k, v in params.items() if v is not None}
    raw = await caller(action, **clean_params)
    return unwrap_action_data(raw)


def is_self_event(event=None, raw_event=None) -> bool:
    """Determine whether an incoming message or notice was generated by the bot itself."""
    if raw_event is not None:
        if read_field(raw_event, "post_type") == "message_sent":
            return True
        self_id = read_field(raw_event, "self_id")
        if self_id in (None, ""):
            self_obj = read_field(raw_event, "self")
            self_id = read_field(self_obj, "user_id")
        user_id = read_field(raw_event, "user_id")
        if user_id in (None, ""):
            sender = read_field(raw_event, "sender")
            user_id = read_field(sender, "user_id")
        if self_id not in (None, "") and user_id not in (None, "") and str(self_id) == str(user_id):
            return True

    if event is not None:
        get_self_id = getattr(event, "get_self_id", None)
        get_sender_id = getattr(event, "get_sender_id", None)
        try:
            bot_self_id = get_self_id() if callable(get_self_id) else None
            sender_id = get_sender_id() if callable(get_sender_id) else None
            if bot_self_id not in (None, "") and sender_id not in (None, "") and str(bot_self_id) == str(sender_id):
                return True
        except Exception:
            pass

    return False


def cq_unescape(value: str) -> str:
    return (
        value
        .replace("&#91;", "[")
        .replace("&#93;", "]")
        .replace("&#44;", ",")
        .replace("&amp;", "&")
    )


def parse_cq_segments(message: str) -> List[Dict]:
    segments = []
    pos = 0
    text = message or ""
    for match in CQ_SEGMENT_RE.finditer(text):
        if match.start() > pos:
            plain = cq_unescape(text[pos:match.start()])
            if plain:
                segments.append({"type": "text", "data": {"text": plain}})
        segment_type = match.group(1)
        raw_params = match.group(2) or ""
        data = {}
        for part in raw_params.split(","):
            if not part or "=" not in part:
                continue
            key, value = part.split("=", 1)
            data[key] = cq_unescape(value)
        segments.append({"type": segment_type, "data": data})
        pos = match.end()
    if pos < len(text):
        trailing = cq_unescape(text[pos:])
        if trailing:
            segments.append({"type": "text", "data": {"text": trailing}})
    return segments


def normalize_message_segments(message) -> List[Dict]:
    if isinstance(message, list):
        return [segment for segment in message if isinstance(segment, dict)]
    if isinstance(message, dict) and message.get("type"):
        return [message]
    if isinstance(message, str):
        if "[CQ:" in message:
            return parse_cq_segments(message)
        if message.strip():
            return [{"type": "text", "data": {"text": message}}]
    return []


def sanitize_remote_filename(filename: str, fallback: str = "file", max_length: int = 180) -> str:
    """Clean a filename for OpenList storage while preserving valid punctuation and extension."""
    raw = str(filename or "").strip()
    raw = raw.replace("\\", "/").split("/")[-1]
    cleaned = "".join(
        c for c in raw
        if ord(c) >= 32 and ord(c) != 127 and c not in '<>:"/\\|?*'
    ).strip(" .")
    if not cleaned:
        cleaned = fallback

    stem, ext = os.path.splitext(cleaned)
    if len(ext) > 32:
        stem = cleaned
        ext = ""
    if len(stem) + len(ext) > max_length:
        keep_stem = max(1, max_length - len(ext))
        stem = stem[:keep_stem].rstrip(" .") or fallback[:keep_stem]
    result = f"{stem}{ext}".strip(" .")
    return result or fallback


def sanitize_relative_subpath(rel_path: str, fallback_name: str = "file") -> str:
    """Normalize a relative path (e.g. from Flash Transfer nested dirs) and block '..' traversal."""
    normalized = str(rel_path or "").replace("\\", "/").strip("/")
    parts = []
    raw_parts = [p for p in normalized.split("/") if p and p not in (".", "..")]
    if not raw_parts:
        return sanitize_remote_filename(fallback_name, fallback="file")
    for idx, part in enumerate(raw_parts):
        is_last = idx == len(raw_parts) - 1
        safe_part = sanitize_remote_filename(part, fallback="file" if is_last else "folder")
        if safe_part and safe_part not in (".", ".."):
            parts.append(safe_part)
    return "/".join(parts) if parts else sanitize_remote_filename(fallback_name, fallback="file")


def extract_flash_share_code_from_url(url: str) -> Tuple[Optional[str], Optional[str]]:
    """Return (fileset_id_if_known, share_code) parsed from a qfile.qq.com URL."""
    if not url or "qfile.qq.com" not in url.lower():
        return None, None
    cleaned_url = url.strip().rstrip(".,;!)）】>\"'")
    parsed = urlparse(cleaned_url)
    query = parse_qs(parsed.query or "")
    for key in ("fileset_id", "fileSetId", "file_set_id"):
        vals = query.get(key)
        if vals and vals[0].strip():
            return vals[0].strip(), None
    for key in ("share_code", "shareCode", "code", "s", "id"):
        vals = query.get(key)
        if vals and vals[0].strip():
            return None, vals[0].strip()

    path_parts = [unquote(p).strip() for p in (parsed.path or "").split("/") if p.strip()]
    if len(path_parts) >= 2 and path_parts[0].lower() in ("q", "s", "f", "share"):
        return None, path_parts[1]
    if path_parts:
        last = path_parts[-1]
        if last.lower() not in ("index.html", "index.htm", "q"):
            return None, last
    return None, None


def extract_flash_descriptors_from_text(text: str) -> List[Dict]:
    """Extract Flash Transfer descriptors from free text containing qfile.qq.com links."""
    if not text or "qfile.qq.com" not in text.lower():
        return []
    descriptors = []
    seen = set()
    for match in FLASH_URL_RE.finditer(text):
        raw_url = match.group(0).rstrip(".,;!)）】>\"'")
        fileset_id, share_code = extract_flash_share_code_from_url(raw_url)
        key = fileset_id or share_code or raw_url
        if not key or key in seen:
            continue
        seen.add(key)
        descriptors.append({
            "fileset_id": fileset_id,
            "share_code": share_code,
            "url": raw_url,
            "title": "",
        })
    return descriptors


def _walk_json_for_flash(node, found_list: List[Dict], seen: set, depth: int = 0):
    if depth > 8 or node is None:
        return
    if isinstance(node, str):
        stripped = node.strip()
        if stripped.startswith(("{", "[")) and ("qfile.qq.com" in stripped or "fileset" in stripped.lower()):
            try:
                parsed = json.loads(stripped)
                _walk_json_for_flash(parsed, found_list, seen, depth + 1)
                return
            except Exception:
                pass
        for desc in extract_flash_descriptors_from_text(stripped):
            key = desc.get("fileset_id") or desc.get("share_code") or desc.get("url")
            if key and key not in seen:
                seen.add(key)
                found_list.append(desc)
        return

    if isinstance(node, dict):
        title = str(node.get("title") or node.get("prompt") or node.get("desc") or "").strip()
        for fs_key in ("fileSetId", "fileset_id", "file_set_id"):
            fs_val = node.get(fs_key)
            if isinstance(fs_val, str) and fs_val.strip():
                fs_id = fs_val.strip()
                if fs_id not in seen:
                    seen.add(fs_id)
                    found_list.append({
                        "fileset_id": fs_id,
                        "share_code": None,
                        "url": "",
                        "title": title,
                    })
        for value in node.values():
            _walk_json_for_flash(value, found_list, seen, depth + 1)
    elif isinstance(node, list):
        for item in node:
            _walk_json_for_flash(item, found_list, seen, depth + 1)


def extract_flash_descriptors_from_segments(segments: List[Dict], include_plain_text: bool = True) -> List[Dict]:
    """Extract deduplicated QQ Flash Transfer descriptors from OneBot message segments."""
    descriptors: List[Dict] = []
    seen = set()

    for segment in segments or []:
        if not isinstance(segment, dict):
            continue
        seg_type = str(segment.get("type") or "").lower()
        data = segment.get("data") or {}
        if not isinstance(data, dict):
            continue

        if seg_type in FLASH_SEGMENT_TYPES:
            fileset_id = (
                data.get("fileSetId")
                or data.get("fileset_id")
                or data.get("file_set_id")
                or data.get("id")
            )
            share_code = data.get("share_code") or data.get("shareCode") or data.get("code")
            url = str(data.get("url") or "").strip()
            if not fileset_id and not share_code and url:
                fileset_id, share_code = extract_flash_share_code_from_url(url)
            key = str(fileset_id or share_code or url or "").strip()
            if key and key not in seen:
                seen.add(key)
                descriptors.append({
                    "fileset_id": str(fileset_id).strip() if fileset_id else None,
                    "share_code": str(share_code).strip() if share_code else None,
                    "url": url,
                    "title": str(data.get("title") or data.get("name") or "").strip(),
                })
        elif seg_type == "json":
            raw_json = data.get("data") if "data" in data else data
            _walk_json_for_flash(raw_json, descriptors, seen)
        elif include_plain_text and seg_type == "text":
            text = str(data.get("text") or "")
            for desc in extract_flash_descriptors_from_text(text):
                key = desc.get("fileset_id") or desc.get("share_code") or desc.get("url")
                if key and key not in seen:
                    seen.add(key)
                    descriptors.append(desc)

    return descriptors


async def resolve_flash_fileset_id(bot_or_event, descriptor: Dict) -> Optional[str]:
    """Resolve a Flash Transfer descriptor into a concrete fileset_id via NapCat API if needed."""
    fileset_id = descriptor.get("fileset_id")
    if fileset_id:
        return str(fileset_id).strip()

    share_code = descriptor.get("share_code")
    raw_url = descriptor.get("url") or ""
    if not share_code and raw_url:
        parsed_fs, parsed_code = extract_flash_share_code_from_url(raw_url)
        if parsed_fs:
            return parsed_fs
        share_code = parsed_code

    candidates = [c for c in (share_code, raw_url) if c]
    for candidate in candidates:
        for param_name in ("share_code", "code", "url"):
            try:
                res = await call_onebot_action(bot_or_event, "get_fileset_id", **{param_name: candidate})
            except Exception as e:
                logger.debug(f"调用 get_fileset_id({param_name}={candidate}) 失败: {e}")
                continue
            if isinstance(res, str) and res.strip():
                return res.strip()
            if isinstance(res, dict):
                for key in ("fileset_id", "fileSetId", "file_set_id", "id"):
                    val = res.get(key)
                    if val not in (None, ""):
                        return str(val).strip()

    # Fallback: in some sharing formats the path token itself is the fileset_id
    return str(share_code).strip() if share_code else None


def _extract_file_entries_from_flash_payload(payload, parent_dir: str = "") -> List[Dict]:
    """Recursively normalize file list payloads returned by get_flash_file_list / get_fileset_info."""
    entries: List[Dict] = []
    if payload is None:
        return entries

    if isinstance(payload, dict):
        # Check if this dict is an envelope containing a list of files
        for list_key in ("file_list", "files", "fileList", "items", "list", "sub_files", "content"):
            sub = payload.get(list_key)
            if isinstance(sub, list):
                return _extract_file_entries_from_flash_payload(sub, parent_dir)
        for nested_key in ("fileset_info", "info", "fileset", "result"):
            nested = payload.get(nested_key)
            if isinstance(nested, (dict, list)):
                extracted = _extract_file_entries_from_flash_payload(nested, parent_dir)
                if extracted:
                    return extracted
        # Otherwise treat dict as a single file entry if it has a name or url
        if any(payload.get(k) for k in ("file_name", "fileName", "name", "url", "download_url", "downloadUrl")):
            payload = [payload]
        else:
            return entries

    if not isinstance(payload, list):
        return entries

    for idx, raw_item in enumerate(payload):
        if not isinstance(raw_item, dict):
            continue

        raw_name = (
            raw_item.get("file_name")
            or raw_item.get("fileName")
            or raw_item.get("name")
            or raw_item.get("title")
            or ""
        )
        is_dir = bool(
            raw_item.get("is_dir")
            or raw_item.get("isDir")
            or raw_item.get("is_folder")
            or raw_item.get("isFolder")
        )
        children = None
        for child_key in ("children", "files", "sub_files", "file_list", "items"):
            if isinstance(raw_item.get(child_key), list):
                children = raw_item.get(child_key)
                break

        item_parent = str(
            raw_item.get("srv_parent_path")
            or raw_item.get("parent_path")
            or raw_item.get("parentPath")
            or raw_item.get("dir")
            or ""
        ).replace("\\", "/").strip("/")

        combined_dir = "/".join(p for p in (parent_dir, item_parent) if p)

        if is_dir or children is not None:
            next_dir = "/".join(p for p in (combined_dir, str(raw_name).strip("/")) if p)
            if children:
                entries.extend(_extract_file_entries_from_flash_payload(children, next_dir))
            continue

        raw_rel = str(
            raw_item.get("relative_path")
            or raw_item.get("relativePath")
            or ""
        ).replace("\\", "/").strip("/")

        file_name = sanitize_remote_filename(str(raw_name), fallback=f"flash_file_{idx + 1}")
        if raw_rel:
            if raw_rel.endswith("/" + str(raw_name)) or raw_rel == str(raw_name):
                rel_path = sanitize_relative_subpath(raw_rel, fallback_name=file_name)
            else:
                rel_path = sanitize_relative_subpath(f"{raw_rel}/{file_name}", fallback_name=file_name)
        elif combined_dir:
            rel_path = sanitize_relative_subpath(f"{combined_dir}/{file_name}", fallback_name=file_name)
        else:
            rel_path = file_name

        file_name = posixpath.basename(rel_path) or file_name
        size = to_int_or_none(
            raw_item.get("file_size")
            if raw_item.get("file_size") is not None
            else raw_item.get("fileSize", raw_item.get("size"))
        )
        direct_url = ""
        for url_key in ("url", "download_url", "downloadUrl", "file_url", "http_url"):
            candidate_url = raw_item.get(url_key)
            if is_http_url(candidate_url):
                direct_url = candidate_url.strip()
                break

        local_path = ""
        for path_key in ("file_path", "filePath", "local_path", "path"):
            candidate_path = raw_item.get(path_key)
            if isinstance(candidate_path, str) and candidate_path and not is_http_url(candidate_path) and os.path.isfile(candidate_path):
                local_path = candidate_path
                break

        file_index = to_int_or_none(
            raw_item.get("cli_file_index")
            if raw_item.get("cli_file_index") is not None
            else raw_item.get("file_index", raw_item.get("fileIndex", raw_item.get("index")))
        )
        entries.append({
            "file_name": file_name,
            "raw_file_name": str(raw_name or file_name),
            "relative_path": rel_path,
            "file_size": size,
            "file_index": file_index if file_index is not None else idx,
            "list_position": idx,
            "cli_fileid": raw_item.get("cli_fileid") or raw_item.get("cliFileId"),
            "svr_fileid": raw_item.get("svr_fileid") or raw_item.get("svrFileId"),
            "file_id": raw_item.get("file_id") or raw_item.get("id"),
            "url": direct_url,
            "local_path": local_path,
        })

    return entries


def _extract_url_from_flash_url_response(res, raw_file_name: str = "", list_position: int = 0) -> Optional[str]:
    if isinstance(res, str) and is_http_url(res):
        return res.strip()
    if isinstance(res, dict):
        for key in ("url", "download_url", "downloadUrl", "file_url", "http_url"):
            val = res.get(key)
            if is_http_url(val):
                return val.strip()
        for list_key in ("urls", "files", "file_list", "list"):
            items = res.get(list_key)
            if isinstance(items, list) and items:
                # Match by filename first if entries are dicts
                for elem in items:
                    if isinstance(elem, dict):
                        ename = elem.get("file_name") or elem.get("fileName") or elem.get("name")
                        if raw_file_name and ename == raw_file_name:
                            u = _extract_url_from_flash_url_response(elem)
                            if u:
                                return u
                if 0 <= list_position < len(items):
                    u = _extract_url_from_flash_url_response(items[list_position])
                    if u:
                        return u
                return _extract_url_from_flash_url_response(items[0])
    if isinstance(res, list) and res:
        if 0 <= list_position < len(res):
            u = _extract_url_from_flash_url_response(res[list_position])
            if u:
                return u
        return _extract_url_from_flash_url_response(res[0])
    return None


async def fetch_flash_file_url(
    bot_or_event,
    fileset_id: str,
    entry: Dict,
    poll_attempts: int = 2,
    poll_delay: float = 0.6,
) -> Optional[str]:
    """Fetch download URL for a specific file inside a QQ Flash Transfer fileset."""
    raw_name = entry.get("raw_file_name") or entry.get("file_name") or ""
    file_index = entry.get("file_index")
    list_pos = entry.get("list_position", 0)
    cli_fileid = entry.get("cli_fileid")
    svr_fileid = entry.get("svr_fileid")

    param_variants = []
    rich_params = {"fileset_id": fileset_id}
    if raw_name:
        rich_params["file_name"] = raw_name
    if file_index is not None:
        rich_params["file_index"] = file_index
    if cli_fileid:
        rich_params["cli_fileid"] = cli_fileid
    if svr_fileid:
        rich_params["svr_fileid"] = svr_fileid
    param_variants.append(rich_params)

    if raw_name and len(rich_params) > 2:
        param_variants.append({"fileset_id": fileset_id, "file_name": raw_name})
    if file_index is not None:
        param_variants.append({"fileset_id": fileset_id, "file_index": file_index})
    param_variants.append({"fileset_id": fileset_id})

    for attempt in range(max(1, poll_attempts)):
        for params in param_variants:
            try:
                res = await call_onebot_action(bot_or_event, "get_flash_file_url", **params)
                url = _extract_url_from_flash_url_response(res, raw_file_name=raw_name, list_position=list_pos)
                if url:
                    return url
            except Exception as e:
                logger.debug(f"调用 get_flash_file_url({params}) 失败: {e}")
        if attempt + 1 < poll_attempts:
            await asyncio.sleep(poll_delay)

    return None


async def resolve_flash_transfer_files(bot_or_event, descriptor: Dict) -> Tuple[Optional[str], List[Dict]]:
    """
    Resolve a Flash Transfer descriptor into (fileset_id, list_of_file_items).
    Each item contains: file_name, relative_path, file_size, url, local_path, fileset_id, refresh_url.
    """
    if not get_bot_caller(bot_or_event):
        return None, []

    fileset_id = await resolve_flash_fileset_id(bot_or_event, descriptor)
    if not fileset_id:
        return None, []

    entries: List[Dict] = []
    for action_name in ("get_flash_file_list", "get_fileset_info"):
        for key_name in ("fileset_id", "fileSetId"):
            try:
                res = await call_onebot_action(bot_or_event, action_name, **{key_name: fileset_id})
                entries = _extract_file_entries_from_flash_payload(res)
                if entries:
                    break
            except Exception as e:
                logger.debug(f"调用 {action_name}({key_name}={fileset_id}) 失败: {e}")
        if entries:
            break

    # Fallback: query get_flash_file_url directly when list API is absent or returns empty
    if not entries:
        try:
            res = await call_onebot_action(bot_or_event, "get_flash_file_url", fileset_id=fileset_id)
            entries = _extract_file_entries_from_flash_payload(res)
            if not entries:
                direct_url = _extract_url_from_flash_url_response(res)
                if direct_url:
                    title = descriptor.get("title") or f"flash_{fileset_id[:10]}"
                    fname = sanitize_remote_filename(title, fallback=f"flash_{fileset_id[:10]}")
                    entries = [{
                        "file_name": fname,
                        "raw_file_name": fname,
                        "relative_path": fname,
                        "file_size": None,
                        "file_index": 0,
                        "list_position": 0,
                        "url": direct_url,
                        "local_path": "",
                    }]
        except Exception as e:
            logger.debug(f"兜底调用 get_flash_file_url(fileset_id={fileset_id}) 失败: {e}")

    # Optional local download_fileset fallback if still empty
    if not entries:
        try:
            dl_res = await call_onebot_action(bot_or_event, "download_fileset", fileset_id=fileset_id)
            entries = _extract_file_entries_from_flash_payload(dl_res)
        except Exception as e:
            logger.debug(f"兜底调用 download_fileset(fileset_id={fileset_id}) 失败: {e}")

    resolved_items: List[Dict] = []
    for entry in entries:
        entry_copy = dict(entry)
        entry_copy["fileset_id"] = fileset_id
        entry_copy["source_type"] = "flash"

        async def _make_refresh(captured_entry: Dict):
            return await fetch_flash_file_url(bot_or_event, fileset_id, captured_entry)

        def _bind_refresh(captured_entry: Dict):
            async def _refresh():
                return await _make_refresh(captured_entry)
            return _refresh

        if not entry_copy.get("url") and not entry_copy.get("local_path"):
            entry_copy["url"] = await fetch_flash_file_url(bot_or_event, fileset_id, entry_copy) or ""
        entry_copy["refresh_url"] = _bind_refresh(entry_copy)
        resolved_items.append(entry_copy)

    return fileset_id, resolved_items


async def resolve_group_file_source(
    bot_or_event,
    group_id,
    file_id: Optional[str],
    busid: int = 0,
    initial_url: str = "",
) -> Dict[str, str]:
    """Resolve a group file into {'url': ..., 'local_path': ...}."""
    if is_http_url(initial_url):
        return {"url": initial_url.strip(), "local_path": ""}
    if not file_id or not get_bot_caller(bot_or_event):
        return {"url": "", "local_path": ""}

    if group_id not in (None, ""):
        try:
            res = await call_onebot_action(
                bot_or_event,
                "get_group_file_url",
                group_id=maybe_int_id(group_id),
                file_id=file_id,
                busid=busid or 0,
            )
            if isinstance(res, dict) and is_http_url(res.get("url")):
                return {"url": res["url"].strip(), "local_path": ""}
        except Exception as e:
            logger.warning(f"获取群文件 URL 失败: group={group_id}, file_id={file_id}, err={e}")

    return await _resolve_via_get_file(bot_or_event, file_id)


async def resolve_private_file_source(
    bot_or_event,
    user_id,
    file_id: Optional[str],
    file_hash: Optional[str] = None,
    initial_url: str = "",
) -> Dict[str, str]:
    """Resolve a private chat file into {'url': ..., 'local_path': ...}."""
    if is_http_url(initial_url):
        return {"url": initial_url.strip(), "local_path": ""}
    if not file_id or not get_bot_caller(bot_or_event):
        return {"url": "", "local_path": ""}

    variants = []
    if user_id not in (None, ""):
        params = {"user_id": maybe_int_id(user_id), "file_id": file_id}
        if file_hash:
            params["file_hash"] = file_hash
        variants.append(params)
    variants.append({"file_id": file_id})

    for params in variants:
        try:
            res = await call_onebot_action(bot_or_event, "get_private_file_url", **params)
            if isinstance(res, dict) and is_http_url(res.get("url")):
                return {"url": res["url"].strip(), "local_path": ""}
            if isinstance(res, str) and is_http_url(res):
                return {"url": res.strip(), "local_path": ""}
        except Exception as e:
            logger.debug(f"调用 get_private_file_url({params}) 失败: {e}")

    return await _resolve_via_get_file(bot_or_event, file_id)


async def resolve_media_segment_source(
    bot_or_event,
    segment_type: str,
    data: Dict,
) -> Dict[str, str]:
    """Resolve image/video segment source via inline url or OneBot get_image/get_file fallback."""
    for url_key in ("url", "file"):
        val = str(data.get(url_key) or "").strip()
        if is_http_url(val):
            return {"url": val, "local_path": ""}
        if url_key == "file" and val and os.path.isfile(val):
            return {"url": "", "local_path": val}

    file_ref = data.get("file_id") or data.get("file")
    if not file_ref or not get_bot_caller(bot_or_event):
        return {"url": "", "local_path": ""}

    if segment_type == "image":
        try:
            res = await call_onebot_action(bot_or_event, "get_image", file=str(file_ref))
            if isinstance(res, dict):
                if is_http_url(res.get("url")):
                    return {"url": res["url"].strip(), "local_path": ""}
                local = res.get("file")
                if isinstance(local, str) and os.path.isfile(local):
                    return {"url": "", "local_path": local}
        except Exception as e:
            logger.debug(f"调用 get_image({file_ref}) 失败: {e}")

    return await _resolve_via_get_file(bot_or_event, str(file_ref))


async def _resolve_via_get_file(bot_or_event, file_id: str) -> Dict[str, str]:
    """Fallback file lookup via OneBot get_file action."""
    if not file_id or not get_bot_caller(bot_or_event):
        return {"url": "", "local_path": ""}
    for key_name in ("file_id", "file"):
        try:
            res = await call_onebot_action(bot_or_event, "get_file", **{key_name: file_id})
            if isinstance(res, dict):
                if is_http_url(res.get("url")):
                    return {"url": res["url"].strip(), "local_path": ""}
                for path_key in ("file", "path", "file_path"):
                    local = res.get(path_key)
                    if isinstance(local, str) and local and os.path.isfile(local):
                        return {"url": "", "local_path": local}
        except Exception as e:
            logger.debug(f"调用 get_file({key_name}={file_id}) 失败: {e}")
    return {"url": "", "local_path": ""}


def extract_history_messages_list(res) -> List[Dict]:
    """Normalize get_friend_msg_history / get_group_msg_history payload into message list."""
    data = unwrap_action_data(res)
    if isinstance(data, list):
        return [m for m in data if isinstance(m, dict)]
    if isinstance(data, dict):
        msgs = data.get("messages")
        if isinstance(msgs, list):
            return [m for m in msgs if isinstance(m, dict)]
    return []
